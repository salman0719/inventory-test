"use client";

import { useActionState } from "react";
import {
  recordReceipt,
  type OrderActionState,
} from "@/app/(app)/purchase-orders/actions";
import { formatQuantity } from "@/lib/product-input";

export type ReceivableLine = {
  id: string;
  productName: string;
  unitOfMeasure: string;
  outstanding: number;
};

/**
 * One delivery, line by line. What arrived is split into accepted, damaged and
 * rejected; only the accepted part becomes stock, so the two discrepancy boxes are
 * pre-filled with zero. A line left at zero across all three boxes did not arrive
 * and is left off the receipt. The hidden idempotency key is generated by the
 * server for this render, so a double submit replays the first receipt instead of
 * posting stock twice.
 */
export function ReceiveForm({
  orderId,
  idempotencyKey,
  lines,
}: {
  orderId: string;
  idempotencyKey: string;
  lines: ReceivableLine[];
}) {
  const [state, formAction, pending] = useActionState<
    OrderActionState,
    FormData
  >(recordReceipt, {});

  return (
    <form action={formAction} className="flex flex-col gap-2">
      <input type="hidden" name="orderId" value={orderId} />
      <input type="hidden" name="idempotencyKey" value={idempotencyKey} />

      <p className="text-[11px] text-ink-muted">
        Pre-filled with what is outstanding. Only the accepted quantity becomes
        stock; note anything damaged or rejected.
      </p>

      <div className="flex flex-col gap-1.5">
        {lines.map((line) => (
          <div
            key={line.id}
            className="flex flex-col gap-1.5 rounded border border-line px-1.5 py-1.5"
          >
            <input type="hidden" name="lineId" value={line.id} />
            <div className="flex items-baseline justify-between gap-2">
              <label
                className="min-w-0 truncate text-[12px]"
                htmlFor={`a-${line.id}`}
              >
                {line.productName}
              </label>
              <span className="shrink-0 text-[10.5px] text-ink-faint">
                {formatQuantity(line.outstanding)} {line.unitOfMeasure} due
              </span>
            </div>

            <div className="grid grid-cols-3 gap-1.5">
              <SplitField
                id={`a-${line.id}`}
                name="accepted"
                label="Accepted"
                defaultValue={String(line.outstanding)}
              />
              <SplitField name="damaged" label="Damaged" defaultValue="0" />
              <SplitField name="rejected" label="Rejected" defaultValue="0" />
            </div>

            <input
              name="reason"
              maxLength={500}
              placeholder="What was wrong? (needed for damaged or rejected)"
              aria-label={`What was wrong with ${line.productName}`}
              className="h-8 rounded border border-line bg-surface px-1.5 text-[11px]"
            />
          </div>
        ))}
      </div>

      {state.error ? (
        <p
          role="alert"
          className="rounded border border-line bg-danger-soft px-2.5 py-2 text-[12px] text-danger"
        >
          {state.error}
        </p>
      ) : null}

      <button
        type="submit"
        disabled={pending}
        className="mt-0.5 inline-flex min-h-[36px] items-center justify-center rounded bg-accent px-3 text-[12px] font-semibold text-on-accent disabled:opacity-60"
      >
        {pending ? "Recording delivery…" : "Receive delivery"}
      </button>
    </form>
  );
}

function SplitField({
  id,
  name,
  label,
  defaultValue,
}: {
  id?: string;
  name: string;
  label: string;
  defaultValue: string;
}) {
  return (
    <label className="flex min-w-0 flex-col gap-0.5">
      <span className="text-[10px] uppercase tracking-[0.06em] text-ink-muted">
        {label}
      </span>
      <input
        id={id}
        name={name}
        inputMode="decimal"
        defaultValue={defaultValue}
        className="h-8 w-full rounded border border-line bg-surface px-1.5 text-right font-mono text-[12px]"
      />
    </label>
  );
}
